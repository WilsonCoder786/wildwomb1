      '1 stuks': '1 piece',
      'blik': 'can',
      'blikken': 'cans',
      'emmer': 'bucket',
      'emmers': 'buckets',
      'kuip': 'tub',
      'kuipen': 'tubs',
      'ca.': 'approx.',
      'rol': 'roll',
      'rollen': 'rolls',
      'pak': 'pack',
      'pakken': 'packs',
      'fles': 'bottle',
      'flessen': 'bottles',
      'vellen': 'sheets',
      'vel': 'sheet',
      'zak': 'bag',
      'zakken': 'bags',
      'koker': 'cartridge',
      'kokers': 'cartridges',
      'plaat': 'board',
      'platen': 'boards',
      'assorti': 'assorted',
      'liter': 'liters',
      '1 liters': '1 liter',
      'bigbags': 'bulk bags',
      'bigbag': 'bulk bag',
      'los gestort': 'bulk delivered',
      'of': 'or',
      'reserve': 'reserve',
    };

    for (final entry in replacements.entries) {
      // Word-boundary or end-of-string replacement
      final regex = RegExp(r'\b' + RegExp.escape(entry.key) + r'\b', caseSensitive: false);
      result = result.replaceAll(regex, entry.value);
    }

    return result;
  }

