class MaterialTranslator {
  /// Translates a material name to English if [isEnglish] is true.
  static String translateName(String name, bool isEnglish) {
    if (!isEnglish) return name;
    final trimmed = name.trim();

    // Direct lookup
    if (_nameMap.containsKey(trimmed)) {
      return _nameMap[trimmed]!;
    }

    // Case-insensitive lookup
    final lower = trimmed.toLowerCase();
    for (final entry in _nameMap.entries) {
      if (entry.key.toLowerCase() == lower) {
        return entry.value;
      }
    }

    // Dynamic Behangplaksel matching (e.g. Behangplaksel (voor 6 rollen))
    if (trimmed.toLowerCase().startsWith('behangplaksel (voor')) {
      return trimmed
          .replaceAll(RegExp('behangplaksel', caseSensitive: false), 'Wallpaper adhesive')
          .replaceAll(RegExp('voor', caseSensitive: false), 'for')
          .replaceAll(RegExp('rollen', caseSensitive: false), 'rolls')
          .replaceAll(RegExp('rol', caseSensitive: false), 'roll');
    }

    // Partial pattern matching
    for (final entry in _patternMap.entries) {
      if (trimmed.contains(entry.key)) {
        return trimmed.replaceAll(entry.key, entry.value);
      }
    }

    return name;
  }

  /// Translates quantity string (e.g. "1 doos", "2 meter", "3 rollen") to English.
  static String translateQty(String qty, bool isEnglish) {
    if (!isEnglish) return qty;
    var result = qty.trim();

    final replacements = {
      'meter': 'meters',
      '1 meters': '1 meter',
      'doos': 'box',
      'dozen': 'boxes',
      'stuk': 'piece',
      'stuks': 'pieces',
